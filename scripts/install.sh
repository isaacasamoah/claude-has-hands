#!/bin/bash
set -euo pipefail

PROJECT_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
NATIVE_HOST_DIR="$PROJECT_ROOT/native-host"

echo "=== Claude Has Hands — Install ==="
echo ""

# ── Preflight Checks ─────────────────────────────────────────────

# Check node is available
if ! command -v node &>/dev/null; then
  echo "ERROR: node is not installed or not in PATH."
  echo "Install Node.js 18+ from https://nodejs.org"
  exit 1
fi

# Check node version (require 18+)
NODE_VERSION=$(node -e "console.log(process.versions.node.split('.')[0])")
if [ "$NODE_VERSION" -lt 18 ]; then
  echo "ERROR: Node.js 18+ is required (found v$(node -v))."
  echo "Install a newer version from https://nodejs.org"
  exit 1
fi

echo "Node.js v$(node -v | tr -d 'v') — OK"

# Check npm
if ! command -v npm &>/dev/null; then
  echo "ERROR: npm is not installed or not in PATH."
  exit 1
fi

echo "npm v$(npm -v) — OK"
echo ""

# ── Build ──────────────────────────────────────────────────────────

echo "Installing dependencies..."
cd "$PROJECT_ROOT" && npm install

echo ""
echo "Building..."
npm run build

echo ""
echo "Making native host executable..."
chmod +x "$NATIVE_HOST_DIR/dist/index.js"
chmod +x "$NATIVE_HOST_DIR/dist/mcp-server.js"

# ── Native-host launcher (node PATH fix) ───────────────────────────
#
# Chrome spawns native-messaging hosts with a minimal PATH (roughly
# /usr/bin:/bin:/usr/sbin:/sbin). A node installed via fnm / nvm / Homebrew is
# NOT on that PATH, so the host's `#!/usr/bin/env node` shebang fails and the
# host never starts — the bridge silently stays offline. We sidestep this by
# resolving node's absolute path NOW (in the user's shell, where node IS found)
# and writing a launcher that hardcodes it. The manifest points at the launcher.
NODE_BIN="$(node -e 'process.stdout.write(process.execPath)')"
LAUNCHER="$NATIVE_HOST_DIR/dist/host-launcher.sh"
cat > "$LAUNCHER" << LAUNCHEOF
#!/bin/bash
# Auto-generated by install.sh — invokes the native host with an absolute node
# path so Chrome's minimal native-messaging PATH can still find node.
exec "$NODE_BIN" "$NATIVE_HOST_DIR/dist/index.js" "\$@"
LAUNCHEOF
chmod +x "$LAUNCHER"
echo "Native host launcher written (node: $NODE_BIN)"

# ── Extension ID ───────────────────────────────────────────────────

EXT_ID="${1:-}"
if [ -z "$EXT_ID" ]; then
  echo ""
  echo "No extension ID provided."
  echo "Load the extension first:"
  echo "  1. Open chrome://extensions"
  echo "  2. Enable Developer Mode"
  echo "  3. Click 'Load unpacked' and select: $PROJECT_ROOT/extension"
  echo "  4. Copy the extension ID and re-run:"
  echo "     $0 <extension-id>"
  echo ""
  echo "Continuing with placeholder ID (you'll need to re-run with the real ID)..."
  EXT_ID="PLACEHOLDER"
fi

# ── Register Native Messaging Host ────────────────────────────────

# Chrome's native-messaging host directory differs by OS. The manifest must
# land where Chrome looks; otherwise the extension can't spawn the bridge.
#   macOS:  ~/Library/Application Support/Google/Chrome/NativeMessagingHosts
#   Linux:  ~/.config/google-chrome/NativeMessagingHosts
PLATFORM="$(uname -s)"
case "$PLATFORM" in
  Darwin)
    MANIFEST_DIR="$HOME/Library/Application Support/Google/Chrome/NativeMessagingHosts"
    ;;
  Linux)
    MANIFEST_DIR="$HOME/.config/google-chrome/NativeMessagingHosts"
    ;;
  *)
    echo "ERROR: unsupported platform '$PLATFORM' (expected Darwin or Linux)" >&2
    exit 1
    ;;
esac

mkdir -p "$MANIFEST_DIR"

MANIFEST_FILE="$MANIFEST_DIR/com.claude.has_hands.json"

cat > "$MANIFEST_FILE" << EOF
{
  "name": "com.claude.has_hands",
  "description": "Claude Has Hands — Browser Automation Host",
  "path": "$LAUNCHER",
  "type": "stdio",
  "allowed_origins": ["chrome-extension://$EXT_ID/"]
}
EOF

echo "Native host manifest written to: $MANIFEST_FILE"

# ── Socket Directory ───────────────────────────────────────────────

SOCKET_DIR="$HOME/.claude/claude-has-hands"
mkdir -p "$SOCKET_DIR"
echo "Socket directory created: $SOCKET_DIR"

# ── MCP Server Config Snippet ─────────────────────────────────────

MCP_CONFIG=$(cat <<JSONEOF
{
  "mcpServers": {
    "browser": {
      "command": "node",
      "args": ["$NATIVE_HOST_DIR/dist/mcp-server.js"]
    }
  }
}
JSONEOF
)

# Write snippet to a file for easy copy
MCP_CONFIG_FILE="$PROJECT_ROOT/.mcp-config.json"
echo "$MCP_CONFIG" > "$MCP_CONFIG_FILE"

# ── Summary ────────────────────────────────────────────────────────

echo ""
echo "╔══════════════════════════════════════════════════════════════╗"
echo "║              Claude Has Hands — Installed                   ║"
echo "╠══════════════════════════════════════════════════════════════╣"
echo "║                                                              ║"
echo "║  Built:                                                      ║"
echo "║    Extension  → extension/dist/background.js                 ║"
echo "║    Native Host → native-host/dist/index.js                   ║"
echo "║    MCP Server  → native-host/dist/mcp-server.js              ║"
echo "║                                                              ║"
echo "║  Native Messaging:                                           ║"
echo "║    $MANIFEST_FILE"
echo "║                                                              ║"
echo "║  MCP Config (copy to settings):                              ║"
echo "║    $MCP_CONFIG_FILE"
echo "║                                                              ║"
echo "║  Test Fixture:                                               ║"
echo "║    file://$PROJECT_ROOT/test/fixture.html"
echo "║                                                              ║"
echo "╚══════════════════════════════════════════════════════════════╝"
echo ""

# Chrome binary path differs by OS — surface the right one in the guidance
# so users can confirm Chrome is actually installed where the manifest expects.
case "$PLATFORM" in
  Darwin) CHROME_BIN="/Applications/Google Chrome.app/Contents/MacOS/Google Chrome" ;;
  Linux)  CHROME_BIN="$(command -v google-chrome 2>/dev/null || echo /usr/bin/google-chrome)" ;;
esac

if [ "$EXT_ID" = "PLACEHOLDER" ]; then
  echo "NEXT STEPS:"
  echo "  1. Open chrome://extensions ($CHROME_BIN)"
  echo "  2. Enable Developer Mode (toggle in top-right)"
  echo "  3. Click 'Load unpacked' → select: $PROJECT_ROOT/extension"
  echo "  4. Copy the extension ID"
  echo "  5. Re-run: $0 <extension-id>"
  echo ""
else
  echo "NEXT STEPS:"
  echo "  1. Add MCP config to Claude Code settings:"
  echo "     cat $MCP_CONFIG_FILE"
  echo ""
  echo "  2. Reload extension if already loaded:"
  echo "     chrome://extensions → click reload on Claude Has Hands"
  echo "     (Chrome binary: $CHROME_BIN)"
  echo ""
  echo "  3. Test with: open chrome and navigate to the test fixture"
  echo "     file://$PROJECT_ROOT/test/fixture.html"
  echo ""
fi

echo "Done."
